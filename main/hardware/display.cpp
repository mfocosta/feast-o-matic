#include <Adafruit_SSD1306.h>
#include "display.h"

static const char *TAG = "display_handler";

/* Forward declaration of feastLogo bitmap */
extern const uint8_t feastLogo[];

#define SCREEN_WIDTH  128  
#define SCREEN_HEIGHT 64  
#define OLED_RESET    -1  /* Not used */

Adafruit_SSD1306 display(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET);
bool isDisplayAvailable = false;

void display_init(void) {
    if (!display.begin(SSD1306_SWITCHCAPVCC, 0x3C)) {
        ESP_LOGW(TAG, "OLED display initialization failed - continuing without display");
        isDisplayAvailable = false;
        return;
    }
    
    isDisplayAvailable = true;
    ESP_LOGI(TAG, "OLED display initialized successfully");
}

/* Function to draw the full screen with a given bitmap */
void display_show_feast_logo(void) {
    display.clearDisplay(); 
    display.drawBitmap(0, 0, feastLogo, 128, 64, WHITE);
    display.display();
}

void display_show_startup(void) {
    if (!isDisplayAvailable) return;
    
    display.clearDisplay();
    display.setTextSize(1.5);
    display.setTextColor(WHITE);
    display.setCursor(0, 0);
    display.println("Sistema Iniciado");
    display.display();
}

void display_show_weight(float weight) {
    if (!isDisplayAvailable) return;
    
    display.setCursor(0, 0);
    display.println("Peso atual:");
    display.setCursor(0, 20);
    display.print(weight, 2);
    display.println(" g");
}

void display_show_dht(float temp, float humidity) {
    if (!isDisplayAvailable) return;
    
    display.setCursor(0, 0);
    display.println("Sensor DHT11:");
    display.print("Temperatura: ");
    display.print(temp);
    display.println(" C");
    display.print("Humidade: ");
    display.print(humidity);
    display.println(" %");
}

void display_show_error(const char* message) {
    if (!isDisplayAvailable) return;
    
    display.clearDisplay();
    display.setCursor(0, 0);
    display.println("ERRO:");
    display.println(message);
}

void display_clear(void) {
    if (!isDisplayAvailable) return;
    
    display.clearDisplay();
}

void display_update(void) {
    if (!isDisplayAvailable) return;

    display.display();
}

